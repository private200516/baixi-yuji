import { readFile, writeFile, mkdir } from 'node:fs/promises';
const directory = 'design/figma-plugin';
await mkdir(directory, { recursive: true });
const [helper, boards, regions, runtime] = await Promise.all([
  readFile('.delivery/figma/helper.js', 'utf8'),
  readFile('.delivery/figma/boards.json', 'utf8'),
  readFile('design/component-regions.json', 'utf8'),
  readFile('scripts/figma-plugin-runtime.js', 'utf8'),
]);
if (!helper.includes('const explicitSemanticIds=null;')) throw new Error('Generate default dynamic-variable payloads before bundling the portable plugin; do not use a fixed variable map.');
const code = `// 白溪舆记 — offline, editable Figma design importer.\n// Generated by scripts/build-figma-plugin.mjs. No network or screenshot layers.\nconst BOARDS=${boards};\nconst REGIONS=${regions};\n${helper}\n${runtime}`;
await writeFile(`${directory}/code.js`, code);
await writeFile(`${directory}/manifest.json`, JSON.stringify({ name: '白溪舆记 · 完整设计导入', id: 'baixi-yuji-offline-design-import', api: '1.0.0', main: 'code.js', editorType: ['figma'], documentAccess: 'dynamic-page', networkAccess: { allowedDomains: ['none'] } }, null, 2));
console.log(JSON.stringify({ files: ['manifest.json', 'code.js'], bytes: Buffer.byteLength(code), artboards: JSON.parse(boards).length }));
